"""
build_benchmark.py

Generates a labelled retrieval benchmark covering every paper in the
corpus, tagged with the train/validation/test split from eval/splits.json.

Hand writing questions does not scale past the sixteen papers of Phase 2:
fifty papers need on the order of two hundred labelled queries for the
per-split numbers to mean anything. So questions are generated by the
local LLM from individual chunks, and the answer evidence is chosen
automatically.

The part that makes this a real test rather than a keyword echo is how
`must_contain` is picked. It is a high-IDF term taken from the source
chunk that does **not** appear in the generated question. A query can only
score by retrieving the passage on meaning or on neighbouring context, not
by matching a term the question already handed it. Those are exactly the
cases the Phase 2 evaluation found hardest.

Every generated query is verified answerable before it is written: the
named paper must contain a chunk holding all required phrases.

Usage:
    python -m scripts.build_benchmark --per-paper 4
    python -m scripts.build_benchmark --per-paper 2 --out eval/benchmark_small.json
"""

import argparse
import json
import random
import re
import sys
from collections import Counter
from pathlib import Path
from typing import List

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import ollama

from src.bm25 import BM25Index, tokenize
from src.corpus import Corpus
from src.embedder import Embedder
from src.llm import LLM_MODEL_NAME
from src.splits import resolve, summarize

QUESTION_PROMPT = (
    "Below is a passage from a research paper.\n\n"
    "Write ONE specific question that this passage answers. The question must:\n"
    "- be answerable using only this passage\n"
    "- be phrased in YOUR OWN WORDS, as a researcher would ask it before\n"
    "  having read the passage\n"
    "- avoid reusing the passage's distinctive wording: prefer ordinary\n"
    "  synonyms and plain phrasing over the paper's own terminology\n"
    "- still be specific about what is being asked\n"
    "- not mention 'the passage', 'the excerpt', or 'this text'\n"
    "- be a single line, no preamble\n\n"
    "Passage:\n{passage}\n\n"
    "Question:"
)

# A question that simply echoes its source chunk makes the benchmark a
# keyword-matching test and flatters lexical retrieval. Measured on the
# first generation, 64.6% of question terms also appeared in the chunk,
# and BM25 alone then beat the full pipeline, which contradicted the
# hand-written query set. Questions above this overlap are rejected.
MAX_QUESTION_CHUNK_OVERLAP = 0.45

# Terms that are rare corpus-wide but useless as evidence: pure numbers,
# single letters, and fragments left by equation extraction.
_EVIDENCE_TOKEN = re.compile(r"^(?=.*[a-z])[a-z0-9][a-z0-9.\-]{2,19}$")


def generate_question(passage: str, model: str) -> str:
    response = ollama.chat(
        model=model,
        messages=[{"role": "user", "content": QUESTION_PROMPT.format(passage=passage[:1500])}],
        options={"temperature": 0.4, "num_ctx": 2048, "num_predict": 60},
    )
    text = response["message"]["content"].strip()
    text = re.sub(r"^(question|q)\s*[:\-]\s*", "", text, flags=re.IGNORECASE).strip()
    return text.strip('"').split("\n")[0].strip()


def usable_question(question: str) -> bool:
    if not (25 <= len(question) <= 220) or "?" not in question:
        return False
    banned = ("passage", "excerpt", "this text", "the above", "the following")
    return not any(b in question.lower() for b in banned)


def lexical_overlap(question: str, chunk_text: str) -> float:
    """Fraction of the question's terms that also occur in the chunk."""
    question_terms = set(tokenize(question))
    if not question_terms:
        return 1.0
    return len(question_terms & set(tokenize(chunk_text))) / len(question_terms)


def pick_evidence(
    chunk_text: str,
    question: str,
    idf: dict,
    document_frequency: Counter,
    max_terms: int = 2,
    min_document_frequency: int = 2,
) -> List[str]:
    """
    Chooses the rarest terms in the chunk that the question does not
    already contain, so retrieval cannot succeed by copying the question.

    Terms occurring in only one chunk corpus-wide are excluded. In a
    corpus with 1950s scans, the very rarest tokens are OCR damage
    ("buftered", "dimenr.ional") rather than meaningful terminology, and
    using those as evidence turns the benchmark into an exact-match test
    for garbage strings. Requiring a term to appear at least twice keeps
    real technical vocabulary and drops one-off scan errors.
    """
    question_tokens = set(tokenize(question))
    counts = Counter(tokenize(chunk_text))
    candidates = [
        term for term in counts
        if term not in question_tokens
        and _EVIDENCE_TOKEN.match(term)
        and term in idf
        and document_frequency.get(term, 0) >= min_document_frequency
    ]
    candidates.sort(key=lambda t: (-idf[t], t))
    return candidates[:max_terms]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=Path("eval/benchmark.json"))
    ap.add_argument("--per-paper", type=int, default=4)
    ap.add_argument("--min-words", type=int, default=70)
    ap.add_argument("--model", default=LLM_MODEL_NAME)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--max-overlap", type=float, default=MAX_QUESTION_CHUNK_OVERLAP,
                    help=("reject questions sharing more than this fraction of their "
                          "terms with the source chunk"))
    args = ap.parse_args()

    rng = random.Random(args.seed)
    corpus = Corpus(Embedder())
    titles = {d.doc_id: d.title for d in corpus.documents}
    split_map = resolve(titles)
    print(summarize(split_map, titles), "\n")

    bm25 = BM25Index()
    bm25.build(corpus.store.chunks)
    idf = bm25.inverse_document_frequency
    document_frequency: Counter = Counter()
    for counts in bm25.doc_token_counts:
        document_frequency.update(counts.keys())

    by_doc = {}
    for chunk in corpus.store.chunks:
        if chunk.word_count >= args.min_words:
            by_doc.setdefault(chunk.doc_id, []).append(chunk)

    which_split = {
        doc_id: name
        for name in ("train", "val", "test")
        for doc_id in split_map[name]["doc_ids"]
    }

    queries, skipped = [], 0
    for n, (doc_id, title) in enumerate(sorted(titles.items(), key=lambda kv: kv[1]), 1):
        chunks = by_doc.get(doc_id, [])
        if not chunks:
            print(f"  no long-enough chunks: {title[:50]}")
            continue
        for chunk in rng.sample(chunks, min(args.per_paper, len(chunks))):
            try:
                question = generate_question(chunk.text, args.model)
            except Exception as error:
                print(f"  generation failed: {error}")
                skipped += 1
                continue
            if not usable_question(question):
                skipped += 1
                continue
            if lexical_overlap(question, chunk.text) > args.max_overlap:
                skipped += 1
                continue
            evidence = pick_evidence(chunk.text, question, idf, document_frequency)
            if not evidence:
                skipped += 1
                continue
            queries.append({
                "id": f"{doc_id[:6]}-{len(queries):03d}",
                "lexical_overlap": round(lexical_overlap(question, chunk.text), 3),
                "split": which_split[doc_id],
                "paper": title,
                "doc_id": doc_id,
                "question": question,
                "must_contain": evidence,
                "source_chunk": chunk.chunk_id,
            })
        if n % 10 == 0:
            print(f"  [{n}/{len(titles)} papers] {len(queries)} queries", flush=True)

    # Verify every query is answerable before writing, so a failing score
    # can only mean the system missed it, never that the test is broken.
    by_id = {}
    for chunk in corpus.store.chunks:
        by_id.setdefault(chunk.doc_id, []).append(chunk.text.lower())

    verified = []
    for query in queries:
        if any(all(p in text for p in query["must_contain"])
               for text in by_id[query["doc_id"]]):
            verified.append(query)
        else:
            skipped += 1

    counts = Counter(q["split"] for q in verified)
    args.out.write_text(json.dumps({
        "description": (
            "Auto-generated retrieval benchmark over the 50-paper corpus. Questions "
            "written by the local LLM from individual chunks; evidence terms chosen "
            "as the rarest chunk terms absent from the question, then verified "
            "answerable. Split labels come from eval/splits.json."
        ),
        "relevance_rule": (
            "A retrieved chunk is relevant if it comes from the paper named in "
            "`paper` AND contains every phrase in `must_contain` (case-insensitive)."
        ),
        "counts": dict(counts),
        "queries": verified,
    }, indent=1), encoding="utf-8")

    print(f"\nwrote {len(verified)} verified queries to {args.out} ({skipped} skipped)")
    for split in ("train", "val", "test"):
        print(f"  {split:<6} {counts.get(split, 0)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
